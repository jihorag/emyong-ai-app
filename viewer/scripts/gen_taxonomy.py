ROMAN = ['I','II']

def slug(s, i):
    base = re.sub(r'[^0-9a-zA-Z가-힣]+','_', s).strip('_')[:20]
    return base or f'u{i}'

def build(sid, name, edu, curr, gakron):
    areas = []
    # I. 교육론
    areas.append({'name': f'{name}교육론', 'no':'I', 'group':None,
        'units':[{'id':f'{sid}__edu__{i:02d}','title':t} for i,t in enumerate(edu)]})
    # II. 교육과정
    areas.append({'name': f'{name}과 교육과정', 'no':'II', 'group':None,
        'units':[{'id':f'{sid}__curr__{i:02d}','title':t} for i,t in enumerate(curr)]})
    # 각론 (group)
    for ai,(aname,units) in enumerate(gakron.items(), start=1):
        areas.append({'name':aname, 'no':ai, 'group':'각론',
            'units':[{'id':f'{sid}__g{ai}__{slug(aname,ai)}_{ui:02d}','title':t}
                     for ui,t in enumerate(units)]})
    return {'subject_id':sid, 'subject':name, 'areas':areas}

os.makedirs(OUT, exist_ok=True)
total_units = 0
for sid,(name,edu,curr,gakron) in DATA.items():
    model = build(sid, name, edu, curr, gakron)
    n = sum(len(a['units']) for a in model['areas'])
    total_units += n
    path = os.path.join(OUT, f'{sid}.json')
    with open(path,'w',encoding='utf-8') as f:
        json.dump(model, f, ensure_ascii=False, indent=2)
    print(f'  {sid}.json  ({name}) — {len(model["areas"])} areas, {n} units')
print(f'총 {len(DATA)}과목, {total_units} units 생성')
